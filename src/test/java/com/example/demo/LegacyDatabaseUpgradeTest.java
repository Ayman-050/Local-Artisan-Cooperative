package com.example.demo;

import com.example.demo.model.Customer;
import com.example.demo.model.User;
import com.example.demo.repository.CustomerRepository;
import com.example.demo.repository.ProductRepository;
import com.example.demo.repository.UserRepository;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.csrf;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Upgrading a database that was created by the OLD version of the app (GitHub main before this work):
 * fewer columns, no notifications table, plain-text passwords, phones on customers. The app must start
 * (Flyway baseline + V1.1 catch-up + V2 + V3, then Hibernate schema validation) and keep the old data usable.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
class LegacyDatabaseUpgradeTest {

    private static final String URL = "jdbc:h2:mem:legacy;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;"
            + "DEFAULT_NULL_ORDERING=HIGH;NON_KEYWORDS=DATE,TIMESTAMP,TYPE,VALUE;DB_CLOSE_DELAY=-1";

    /** Schema as generated by Hibernate ddl-auto=update from the old entities, with a little data. */
    private static final String[] LEGACY_SCHEMA = {
            "create table users (user_id bigint generated by default as identity primary key, name varchar(255), "
                    + "email varchar(255), password varchar(255), role varchar(255), profile_picture text)",
            "create table customers (user_id bigint not null primary key references users, address varchar(255), phone varchar(255))",
            "create table artisans (user_id bigint not null primary key references users, shop_name varchar(255), biography varchar(255))",
            "create table admins (user_id bigint not null primary key references users)",
            "create table product_categories (category_id bigint generated by default as identity primary key, name varchar(255))",
            "create table products (id bigint generated by default as identity primary key, title varchar(255), "
                    + "description varchar(1000), price float(53) not null, category varchar(255), image_url varchar(255), "
                    + "stock_quantity integer not null, artisan_name varchar(255), is_auction_item boolean not null, "
                    + "adding_date date, artisan_id bigint references artisans, category_id bigint references product_categories)",
            "create table orders (order_id bigint generated by default as identity primary key, date date, status varchar(255), "
                    + "total_amount float(53) not null, shipping_address varchar(255), customer_id bigint references customers)",
            "create table order_items (order_item_id bigint generated by default as identity primary key, quantity integer not null, "
                    + "price float(53) not null, order_id bigint references orders, product_id bigint references products)",
            "create table payments (payment_id bigint generated by default as identity primary key, transaction_details varchar(255), "
                    + "date date, status varchar(255), amount float(53) not null, payment_method varchar(255), order_id bigint unique references orders)",
            "create table auctions (id bigint generated by default as identity primary key, product_id bigint unique references products, "
                    + "starting_bid float(53) not null, current_highest_bid float(53) not null, highest_bidder_name varchar(255), "
                    + "start_time timestamp(6), end_time timestamp(6), status varchar(255), admin_id bigint references admins)",
            "create table bids (bid_id bigint generated by default as identity primary key, bid_amount float(53) not null, "
                    + "bid_time timestamp(6), customer_id bigint references customers, auction_id bigint references auctions)",
            "create table reviews (review_id bigint generated by default as identity primary key, rating integer not null, "
                    + "comment varchar(255), date date, customer_id bigint references customers, product_id bigint references products)",
            "create table addresses (id bigint generated by default as identity primary key, user_email varchar(255), label varchar(255), "
                    + "street varchar(500), city varchar(255), zip varchar(255), country varchar(255), is_default boolean not null)",
            "create table wishlists (wishlist_id bigint generated by default as identity primary key, date_created date, "
                    + "customer_id bigint unique references customers)",
            "create table wishlist_items (wishlist_item_id bigint generated by default as identity primary key, date_added date, "
                    + "wishlist_id bigint references wishlists, product_id bigint references products)",
            // Data: a customer with a plain-text password, an artisan, a product, a delivered order with a review.
            "insert into users (user_id, name, email, password, role) values (900, 'Old Customer', 'old@legacy.test', 'oldPass1', 'CUSTOMER')",
            "insert into customers (user_id, address, phone) values (900, 'Manama', '+97311112222')",
            "insert into users (user_id, name, email, password, role) values (901, 'Old Artisan', 'oldart@legacy.test', 'oldPass1', 'ARTISAN')",
            "insert into artisans (user_id, shop_name) values (901, 'Old Shop')",
            "insert into products (id, title, price, stock_quantity, is_auction_item, artisan_id, artisan_name) "
                    + "values (900, 'Old Vase', 12.5, 3, false, 901, 'Old Artisan')",
            "insert into orders (order_id, date, status, total_amount, customer_id) values (900, CURRENT_DATE, 'delivered', 14.5, 900)",
            "insert into order_items (order_item_id, quantity, price, order_id, product_id) values (900, 1, 12.5, 900, 900)",
            "insert into reviews (review_id, rating, comment, date, customer_id, product_id) values (900, 5, 'Nice', CURRENT_DATE, 900, 900)",
    };

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement s = c.createStatement()) {
            for (String sql : LEGACY_SCHEMA) {
                s.execute(sql);
            }
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Autowired
    MockMvc mvc;
    @Autowired
    UserRepository userRepository;
    @Autowired
    CustomerRepository customerRepository;
    @Autowired
    ProductRepository productRepository;

    @Test
    void oldDatabaseIsUpgradedAndItsDataStillWorks() throws Exception {
        // The app started, so migrations ran and the schema validated. Now check the data.
        User customer = userRepository.findById(900L).orElseThrow();
        assertThat(customer.getStatus()).isEqualTo("active");
        assertThat(customer.getPhone()).isEqualTo("+97311112222");
        assertThat(customer.getPassword()).startsWith("$2"); // plain text was hashed at startup
        assertThat(((Customer) customer).getTotalSpent()).isNotNull();
        // The old app had no approval step, so existing artisans stay usable.
        assertThat(userRepository.findById(901L).orElseThrow().getStatus()).isEqualTo("active");
        assertThat(productRepository.findById(900L).orElseThrow().getStatus()).isEqualTo("active");

        // The old customer can log in with their old password and use the new features.
        var session = mvc.perform(post("/api/auth/login").with(csrf()).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"old@legacy.test\",\"password\":\"oldPass1\"}"))
                .andExpect(status().isOk())
                .andReturn().getRequest().getSession(false);
        mvc.perform(get("/api/orders").session((org.springframework.mock.web.MockHttpSession) session))
                .andExpect(status().isOk());
        mvc.perform(get("/api/notifications/900").session((org.springframework.mock.web.MockHttpSession) session))
                .andExpect(status().isOk());
        mvc.perform(get("/ProductDetailsStandard").param("id", "900")).andExpect(status().isOk());
    }
}
