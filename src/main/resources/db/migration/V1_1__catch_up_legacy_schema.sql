-- 4. Older versions kept customer phone numbers in customers.phone; the app now reads users.phone.
--    (Adding customers.phone where it is missing is harmless; Hibernate ignores extra columns.)
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone varchar(255);
UPDATE users SET phone = (SELECT c.phone FROM customers c WHERE c.user_id = users.user_id)
    WHERE phone IS NULL AND EXISTS (SELECT 1 FROM customers c WHERE c.user_id = users.user_id AND c.phone IS NOT NULL);
