-- V1.1: bring databases created by OLDER versions of the app up to the V1 baseline.
-- Databases created by the old ddl-auto=update code can miss tables and columns (e.g. customers.total_spent,
-- users.status, the notifications table). Every statement here is "if not exists", so on an up-to-date or
-- brand-new database this migration changes nothing. Written for both PostgreSQL and H2 (tests).

-- 1. Missing tables (same definitions as V1, without foreign keys).
CREATE TABLE IF NOT EXISTS addresses (
    is_default boolean not null,
    id bigint generated by default as identity,
    street varchar(500),
    city varchar(255),
    country varchar(255),
    label varchar(255),
    user_email varchar(255),
    zip varchar(255),
    primary key (id)
);
