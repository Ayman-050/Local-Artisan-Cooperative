    primary key (order_item_id)
);
CREATE TABLE IF NOT EXISTS orders (
    date date,
    total_amount float(53) not null,
    customer_id bigint,
    order_id bigint generated by default as identity,
    shipping_address varchar(255),
    status varchar(255),
    primary key (order_id)
